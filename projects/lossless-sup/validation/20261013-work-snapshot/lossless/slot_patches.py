"""Reviewed 5.02 instruction sites for the optional expanded-slot candidate.

No camera I/O. Generate declarations consumed by the existing LOSS builder;
the loader remains the sole owner of claims and power-off restoration.
"""
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent / 'native'
META = json.loads((HERE / 'slot_sites.json').read_text())
SITES = {int(a, 16): (v, 'expanded recording slots') for a, v in META['stock'].items()}
# C037DF40's re-dispatch guard (slot_sites.json 'writer_guard'): stock word, new word.
GUARD = [(int(a, 16), s, n) for a, s, n in META.get('writer_guard', {}).get('words', [])]
SITES.update({a: (s, 'writer re-dispatch guard') for a, s, _ in GUARD})
SLOT_MAX = int(re.search(r'^#define FPL_SLOT_MAX (\d+)u$',
                        (HERE / 'slot_capacity.h').read_text(), re.M)[1])


def imm(word, value):
    for rotation in range(16):
        for low in range(256):
            r = rotation * 2
            decoded = ((low >> r) | (low << (32 - r))) & 0xffffffff if r else low
            if decoded == value:
                return (word & ~0xfff) | rotation << 8 | low
    raise ValueError('unencodable ARM immediate')


def generate():
    def stock(a): return SITES[a][0]
    if not 128 <= SLOT_MAX <= 1016 or SLOT_MAX % 4:
        raise ValueError('slot capacity exceeds the reviewed native instruction layout')
    claim = ['/* Generated by lossless/slot_patches.py from reviewed slot_sites.json. */',
             f'#define FPL_SLOT_CLAIMS {len(SITES)}', '#ifdef FPL_SLOT_EMIT_CLAIMS']
    claim += [f'    .word 0x{a:08X}, 0x{w:08X}, SL_EXCL' for a, (w, _) in SITES.items()]
    claim += ['#endif', '']
    (HERE / 'slot_claims.inc').write_text('\n'.join(claim))
    lines = ['/* Generated by lossless/slot_patches.py; no runtime site discovery. */',
             f'_Static_assert(FPL_SLOT_MAX == {SLOT_MAX}u, "regenerate and review native slot layout");',
             'static uint32_t slot_sites_stock(void) {']
    lines += [f'    if (*(volatile uint32_t *)0x{a:08x}u != 0x{w:08x}u) return 0;' for a, (w, _) in SITES.items()]
    lines += ['    return 1;', '}', 'static void slot_patch_layout(struct fpl_slot_runtime *s) {']
    for a in META['controls']:
        offset = (stock(a) & 0xfff) + (SLOT_MAX - 96) * 4
        if offset > 0xfff:
            raise ValueError(f'registry control at {a:#x} exceeds imm12')
        new = (stock(a) & ~0xfff) | offset
        lines.append(f'    slot_write(0x{a:08x}u, 0x{new:08x}u);')
    # Lookup bounds cover the whole table; scan ends follow the active count.
    for a in META['counts']:
        lines.append(f'    slot_write(0x{a:08x}u, 0x{imm(stock(a), SLOT_MAX):08x}u);')
    for a in META['pointers'] + [META['registry']]:
        value = '(uintptr_t)&s->pool_ptr' if a in META['pointers'] else '(uintptr_t)s->registry'
        for off in (0, 4):
            lines.append(f'    slot_write(0x{a+off:08x}u, slot_mov16(0x{stock(a+off):08x}u, ({value}) >> {16 if off else 0}));')
    # One writer message per frame: see slot_sites.json 'writer_guard'.
    for a, _, n in GUARD:
        lines.append(f'    slot_write(0x{a:08x}u, 0x{n:08x}u);')
    lines += ['}', 'static void slot_patch_count(uint32_t n) {']
    # Registry scans stop at the active pool: stock words at 96, otherwise
    # #(n*4) as imm8 (n/4) rotated by 28. Unused tail entries stay zero.
    for a in META['ends']:
        if imm(stock(a), 96 * 4) != stock(a):
            raise ValueError(f'scan end at {a:#x} is not #0x180')
        lines.append(f'    slot_write(0x{a:08x}u, n == FPL_SLOT_STOCK ? 0x{stock(a):08x}u : '
                     f'(0x{stock(a)&~0xfff:08x}u | 0xe00u | (n >> 2)));')
    # n is rounded to four: n/4 fits imm8 at every supported capacity.
    for a in META['runtime'][:2]:
        lines.append(f'    slot_write(0x{a:08x}u, (0x{stock(a)&~0xfff:08x}u | 0xf00u | (n >> 2)));')
    for a in META['bounds']:
        for off in (0, 4):
            lines.append(f'    slot_write(0x{a+off:08x}u, slot_mov16(0x{stock(a+off):08x}u, ((n-1u)*0x1128u) >> {16 if off else 0}));')
    lines += ['}', '']
    (HERE / 'slot_patches.h').write_text('\n'.join(lines))


if __name__ == '__main__':
    generate()
