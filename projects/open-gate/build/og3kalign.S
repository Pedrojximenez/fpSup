.syntax unified
.arm
.text
/* ============================================================================
 * og3kalign — 讓 OG3K 的記錄尺寸遵守 fp 自己的邊界慣例。
 * ============================================================================
 * 2026-09-13 統計原廠所有影片錄影 profile:
 *
 *     p171 (UHD)  記錄 3856x2170  裁切 3840x2160  邊界 +16/+10  16對齊 ✓
 *     p173 (FHD)  記錄 1936x1090  裁切 1920x1080  邊界 +16/+10  16對齊 ✓
 *     p83  (借的) 記錄 3032x2012  裁切 3008x2000  邊界 +24/+12  16對齊 ✗
 *
 * **每一個原廠影片 profile 都是 +16/+10 而且寬度是 16 的倍數。**
 * p83 是**照片** profile,用的是感測器視窗尺寸 3032x2012,兩個邊界都不同,
 * 而且 3032 = 8 x 379 只有 8 對齊。
 *
 * 這很可能就是機內回放花屏的根因:回放的顯像路徑只在原廠尺寸
 * (1936 / 3856,都 16 對齊)上被驗證過。先前我曾用「S 尺寸照片就是 3032 寬
 * 而且檢視正常」否定過這個假設 —— 但後來查清楚**照片檢視根本不解 RAW**,
 * 它顯示的是內嵌的 JPEG 預覽,所以那個反例是假的。
 *
 * 依慣例,3008x2000 的記錄尺寸應該是 **3024x2010**,裁切原點 (8,5)。
 *
 * 做法:畫布是每次載入複製到 RAM 的一份,在 0xC043A19C(c0439d18 之後、
 * c0434ec0 之前)改那份複本 —— **原廠 PARAM 列一個位元都不動**。
 *
 * ⚠️ 這是**錄影路徑**的改動。2026-09-12 有過「宣告的尺寸與 producer 實際
 * 產出不一致 → 錄出來的 DNG 只有左上一塊有畫面」的事故,毀掉數十段素材。
 * **每次改動都必須錄一小段、抓一張 DNG 解檔驗證之後才算數。**
 *
 * Hook:0xC043A19C(BL,回放位移的 mov r0,r4)。r5 = profile id。
 * LOG(0xC0732600):+0 命中次數  +4 最後看到的 profile id
 * ========================================================================== */

.equ ROW,  0x5C
.equ LOG,  0xC0732600
.equ PROF, 83
.equ NEW_W, 3024                /* 3008 + 16 */
.equ NEW_H, 2010                /* 2000 + 10 */

.macro LDA reg, value
    movw    \reg, #:lower16:\value
    movt    \reg, #:upper16:\value
.endm

.global entry
entry:
    push    {r0, r1, r2, r3, ip, lr}

    cmp     r5, #PROF
    bne     out

    add     r1, r4, #ROW                @ 畫布
    LDA     ip, LOG
    ldr     r3, [ip]
    add     r3, r3, #1
    str     r3, [ip]
    str     r5, [ip, #4]

    movw    r3, #NEW_W
    str     r3, [r1, #0x00]             @ 記錄寬  3032 → 3024
    movw    r3, #NEW_H
    str     r3, [r1, #0x04]             @ 記錄高  2012 → 2010

out:
    pop     {r0, r1, r2, r3, ip, lr}
    mov     r0, r4                      @ 位移指令
    bx      lr
