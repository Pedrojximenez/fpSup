.syntax unified
.arm
.text
/* ============================================================================
 * dngblk —— 記下每一格 CinemaDNG 的「標頭區塊長度」desc+0x14C。
 *
 * 2026-09-21:HSW 8-bit 有 31-61% 的格子,DNG 在檔案裡被往後推 7,168 或 65,536
 * 位元組。§67.5 追出來的機制是:每格檔案分兩段寫,第一段是長度 desc+0x14C 的
 * 標頭區塊,而 TIFF 標頭靠右對齊在裡面 —— 區塊比實際標頭(0x13800)大多少,
 * 開頭就多幾個零。三種位移正好對應三個區塊長度:
 *
 *     0x13800 = 79,872    -> 位移 0
 *     0x15400 = 87,040    -> 位移 7,168     (= 每格的保留量)
 *     0x23800 = 145,408   -> 位移 65,536
 *
 * 但 desc+0x14C 一段錄影只算一次(FUN_c0378A50)、逐格複製(FUN_c0373DD0),
 * 照理是定值。所以要分辨兩件事:
 *     (a) 區塊長度真的逐格變      -> 這支會看到不同的值
 *     (b) 長度不變,是寫入端補零  -> 這支會看到 128 格都一樣
 *
 * 掛在 0xC03A53D0(`ldr r6, [r4, #0x14c]`,r4 = 描述子)。只讀不寫,
 * 不動旗標(只用 add/and/ldr/str),對錄影行為零影響。
 *
 *     RING+0x00  寫入索引(0..127)
 *     RING+0x04  累計格數
 *     RING+0x10  128 筆,每筆 4 bytes = 該格的 desc+0x14C
 * ========================================================================== */

.equ RING, 0xC0730000
.equ BACK, 0xC03A53D4

.global entry
entry:
    ldr     r6, [r4, #0x14c]            @ 位移的原指令
    push    {r0, r1, r2}
    movw    r0, #:lower16:RING
    movt    r0, #:upper16:RING
    ldr     r1, [r0]                    @ idx
    ldr     r2, [r0, #4]
    add     r2, r2, #1
    str     r2, [r0, #4]                @ 累計 +1
    add     r2, r0, r1, lsl #2
    str     r6, [r2, #0x10]             @ 存這一格的區塊長度
    add     r1, r1, #1
    and     r1, r1, #0x7F               @ 128 槽環,and 不動旗標
    str     r1, [r0]
    pop     {r0, r1, r2}
    movw    ip, #:lower16:BACK
    movt    ip, #:upper16:BACK
    bx      ip
