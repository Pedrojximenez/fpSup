/* ============================================================================
 * og3kpbrow — 讓 12-bit 影片回放的畫布認得 3:2 的片子。
 * ============================================================================
 *
 * 為什麼是這個做法(完整推導見 notes/OG3K_PLAYBACK_PROFILE_CLASSES.md):
 *
 *   profile 有「類別」,由 (+0x44, +0x80) 決定。影片回放類是
 *   +0x44 = 1(有壓縮位元流的解碼緩衝)、+0x80 = 0x1000A/9/7(位元深度)。
 *   照片檢視類的 p41-p46 雖然是現成的 3:2 純預覽,但 +0x44 = 0,
 *   壓縮禎沒有地方解碼,所以換 profile 一定黑屏 —— 試過兩次,都是黑的。
 *
 *   名稱表 0xC0BE4508 是「位元深度 × 解析度」,十二格全滿而且全是 16:9,
 *   沒有備用的 3:2 成員可以選;PARAM 列是「每欄一個陣列」也無法新增。
 *
 *   所以這裡不換 profile,而是**改畫布那份 RAM 複本的幾何**。
 *   畫布本來就是每次載入時複製出來的一份,韌體自己也用 +0xD8/+0xE0 覆寫
 *   +0x0C/+0x10 —— 在複本上改幾何是這個設計原本就有的動作。
 *
 * Hook:0xC043A19C。這個位置剛好在 FUN_c0439d18 填好畫布之後、
 * FUN_c0434ec0 依畫布算平面尺寸之前:
 *
 *     C043A198  bl  c0439d18       ; 畫布填好
 *     C043A19C  mov r0, r4         ; <= hook(BL,回放此指令後由 lr 返回)
 *     C043A1B4  bl  c0434ec0       ; 之後才算尺寸
 *
 * ABI:r4 = 物件,r4+0x5C = 畫布,r5 = profile id,
 *     r4+0x08 / r4+0x0C = **呼叫端給的真實片子尺寸**(FUN_c0434e08 設的)。
 *
 * 守衛(2026-09-13 用 pbobs.S 實測後改對的):
 *     畫布 +0x80 的 bit16 有設(壓縮位元流 = 影片回放類)且
 *     PBFLAG == 1(og3kname 看到正在顯示 3008x2000)
 *
 * 原本的守衛兩個都錯,實測才知道:
 *   - 回放載入的是 **p51**(group 0 / UHD,柵格 3856x2170),不是 p73。
 *     位元深度不影響選哪個 profile,所以不能比 +0x80 == 0x10007。
 *     片子是 3032x2012 而柵格是 3856 → stride 對不上 → 雜訊。
 *   - obj+8 不是片源尺寸,是**顯示畫布** 1620x1080。片源尺寸在這個呼叫裡
 *     根本拿不到,只有 og3kname 那個 hook(0xC0437B48)看得到 ——
 *     HUD 上的 "3008x2000" 就是它畫的,它會把 PBFLAG 設起來。
 *
 * 兩個守衛合起來就是「影片回放類的畫布 + 現在顯示的是 3008x2000」=
 * 只有 OG3K 的片子在回放時才成立。live view 的 profile 沒有 bit16,
 * 真的 UHD/FHD 片子會讓 og3kname 把 PBFLAG 清成 0。
 *
 * 寫進去的值**全部從 p43 抄**。p43 是韌體自己給 3032x2012 感測器視窗用的
 * profile,而預覽柵格的四捨五入方式每個模式都不同 —— 2026-09-12 已經證明
 * 算出來的柵格一定是錯的,只能抄。og3k_plan.py 會在組建時對著映像驗證。
 *
 * +0x44 與 +0x80 不動:那是類別,必須留著,否則就回到黑屏。
 * ========================================================================== */

.equ ROW,   0x5C            /* 畫布相對物件的位移 */
.equ LOG,    0xC0732600     /* +0  命中次數(有改)
                               +4  最後改到的 profile id
                               +8  退回:不是影片回放類
                               +12 退回:是影片回放類但 PBFLAG = 0 */
.equ PBFLAG, 0xC0731C0C     /* og3kname 設的:1 = 正在顯示 3008x2000 */

.macro LDA reg, value
    movw    \reg, #:lower16:\value
    movt    \reg, #:upper16:\value
.endm

/* 畫布欄位 off ← 立即值 val(off 是畫布內位移,r1 已經是畫布) */
.macro PUT off, val
    movw    r3, #\val
    movw    r0, #\off
    str     r3, [r1, r0]
.endm

.global entry
entry:
    push    {r0, r1, r2, r3, ip, lr}

    add     r1, r4, #ROW
    LDA     ip, LOG

    /* --- 類別守衛:必須是影片回放類(壓縮位元流)------------------------- */
    movw    r0, #0x80
    ldr     r3, [r1, r0]                @ 畫布 +0x80
    tst     r3, #0x10000                @ bit16 = 壓縮位元流
    beq     notmovie

    /* --- 片源守衛:現在顯示的必須是 3008x2000 ---------------------------- */
    LDA     r0, PBFLAG
    ldr     r3, [r0]
    cmp     r3, #1
    bne     notours

    ldr     r3, [ip]                    @ 命中計次
    add     r3, r3, #1
    str     r3, [ip]
    str     r5, [ip, #4]                @ 最後改到的 profile id

    /* --- 幾何:全部抄自 p43(3032x2012 視窗的原廠 profile) -------------- */
    PUT     0x1C,  2                    @ 3:2 標記(原 1)
    PUT     0x0C,  2024                 @ 預覽柵格(原 1936x1090)
    PUT     0x10,  1341
    PUT     0xD8,  2024                 @ 消費端覆寫,與柵格一致
    PUT     0xE0,  1341
    PUT     0x20,  2000                 @ 預覽可見(原 1920x1080)
    PUT     0x28,  1334
    PUT     0x60,  1536                 @ 預覽 RWZM 1.5x(原 1600)
    PUT     0xD0,  1536
    PUT     0xF4,  3032                 @ 感測器視窗(原 3032x1708,寬度本來就對)
    PUT     0xF8,  2012
    b       out

notmovie:
    ldr     r3, [ip, #8]
    add     r3, r3, #1
    str     r3, [ip, #8]
    b       out

notours:
    ldr     r3, [ip, #12]
    add     r3, r3, #1
    str     r3, [ip, #12]

out:
    pop     {r0, r1, r2, r3, ip, lr}
    mov     r0, r4                      @ 位移指令
    bx      lr
